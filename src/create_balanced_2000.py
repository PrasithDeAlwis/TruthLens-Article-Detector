def preprocess_text(text):
    """
    Preprocessing pipeline following standard NLP practices:
    1. Convert to lowercase
    2. Remove links/URLs
    3. Remove punctuation
    4. Remove numbers
    5. Remove stopwords
    6. Stemming
    """
    # 1. Convert to lowercase
    text = text.lower()
    
    # 2. Remove URLs/Links
    text = re.sub(r'http\S+|www\S+|https\S+', '', text, flags=re.MULTILINE)
    text = re.sub(r'\S+@\S+', '', text)  # Remove emails
    
    # 3 & 4. Remove punctuation and numbers
    text = re.sub(r'[^a-z\s]', '', text)
    
    # 5. Tokenize and remove stopwords
    stop_words = set(stopwords.words('english'))
    words = word_tokenize(text)
    words = [word for word in words if word not in stop_words and len(word) > 2]
    
    # 6. Stemming (Porter Stemmer)
    stemmer = PorterStemmer()
    words = [stemmer.stem(word) for word in words]
    
    return ' '.join(words)


def create_2000_row_balanced_dataset():
    """Create 2000-row dataset (1000 real + 1000 fake)"""
    
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(script_dir)
    data_dir = os.path.join(project_root, 'data')
    
    print("=" * 80)
    print("CREATING BALANCED 2000-ROW DATASET")
    print("1000 Real News + 1000 Fake News")
    print("=" * 80)
    
    # Download NLTK data
    print("\n[0/6] Downloading NLTK data...")
    nltk.download('punkt', quiet=True)
    nltk.download('stopwords', quiet=True)
    print("✓ NLTK data ready")
    
    # Load existing real news
    print("\n[1/6] Loading existing real news...")
    balanced_path = os.path.join(data_dir, 'balanced_training_data.csv')
    if os.path.exists(balanced_path):
        balanced_df = pd.read_csv(balanced_path)
        existing_real = balanced_df[balanced_df['label'] == 'real']
        print(f"✓ Found {len(existing_real)} existing real news")
    else:
        existing_real = pd.DataFrame(columns=['text', 'label'])
        print("✓ No existing real news found")
    
    # Generate additional real news
    print("\n[2/6] Generating additional real news...")
    needed = 1000 - len(existing_real)
    new_real = generate_additional_real_news(needed)
    new_real_df = pd.DataFrame({'text': new_real, 'label': 'real'})
    
    all_real = pd.concat([existing_real[['text', 'label']], new_real_df], ignore_index=True)
    all_real = all_real.head(1000)  # Ensure exactly 1000
    print(f"✓ Total real news: {len(all_real)}")
    
    # Load fake news
    print("\n[3/6] Loading fake news from Kaggle...")
    kaggle_path = os.path.join(data_dir, 'preprocessed_kaggle_data.csv')
    kaggle_df = pd.read_csv(kaggle_path)
    fake_sample = kaggle_df.sample(n=1000, random_state=42)
    fake_sample = fake_sample[['text']].copy()
    fake_sample['label'] = 'fake'
    print(f"✓ Sampled {len(fake_sample)} fake news")
    
    # Combine
    df = pd.concat([all_real, fake_sample], ignore_index=True)
    df = df.sample(frac=1, random_state=42).reset_index(drop=True)
    print(f"\n✓ Combined dataset: {len(df)} articles")
    print(f"  - Real: {(df['label']=='real').sum()}")
    print(f"  - Fake: {(df['label']=='fake').sum()}")
    
    # Preprocessing
    print("\n[4/6] Applying preprocessing pipeline...")
    print("  Steps: Lowercase → Remove Links → Remove Punctuation")
    print("         Remove Numbers → Remove Stopwords → Stemming")
    
    cleaned_texts = []
    for i, text in enumerate(df['text']):
        if (i + 1) % 200 == 0:
            print(f"  - Progress: {i+1}/{len(df)}")
        cleaned = preprocess_text(text)
        cleaned_texts.append(cleaned)
    
    df['cleaned_text'] = cleaned_texts
    
    # Remove empty
    print("\n[5/6] Removing empty texts...")
    df = df[df['cleaned_text'].str.strip() != '']
    df = df[df['cleaned_text'].str.split().str.len() >= 3]
    print(f"✓ Final count: {len(df)} articles")
    
    # Save
    print("\n[6/6] Saving dataset...")
    final_df = df[['text', 'cleaned_text', 'label']]
    output_path = os.path.join(data_dir, 'balanced_2000_dataset.csv')
    final_df.to_csv(output_path, index=False)
    print(f"✓ Saved to: {output_path}")
    
    # Statistics
    print("\n" + "=" * 80)
    print("FINAL DATASET STATISTICS")
    print("=" * 80)
    print(f"  Total articles: {len(final_df)}")
    print(f"  Real news: {(final_df['label']=='real').sum()}")
    print(f"  Fake news: {(final_df['label']=='fake').sum()}")
    print(f"  Balance: {(final_df['label']=='real').sum() / len(final_df) * 100:.1f}% real")
    print(f"  Avg words (original): {final_df['text'].str.split().str.len().mean():.0f}")
    print(f"  Avg words (cleaned): {final_df['cleaned_text'].str.split().str.len().mean():.0f}")
    
